-- =============================================================================
-- 01_schema.sql — 수입검사 및 협력사 품질 평가 (클라우드 버전) DB 구조
--
-- 사용법: Supabase 대시보드 → SQL Editor → New query → 이 파일 내용을 전부 붙여넣고 → Run
--         (여러 번 실행해도 안전하도록 IF NOT EXISTS / OR REPLACE를 썼습니다)
--
-- 데스크톱 앱(SQLite)의 9개 테이블을 PostgreSQL로 그대로 옮겼습니다.
--   기준정보 4개 : supplier, part, defect_type, inspector
--   업무 3개     : lot, inspection, inspection_defect(검사↔불량유형 N:M 연결 표)
--   AQL 기준표 2개: aql_code_letter, aql_plan  (KS Q ISO 2859-1, 검사수준 II)
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. 테이블
-- -----------------------------------------------------------------------------
create table if not exists supplier (
    supplier_id    bigint generated by default as identity primary key,
    code           text not null unique,
    name           text not null,
    contact_person text,
    phone          text
);

create table if not exists part (
    part_id     bigint generated by default as identity primary key,
    part_no     text not null unique,
    name        text not null,
    supplier_id bigint not null references supplier(supplier_id),
    aql         numeric(4,2) not null check (aql in (0.65, 1.0, 1.5, 2.5, 4.0)),
    resumed_at  timestamp                       -- 검사 중지 후 관리자가 재개한 일시
);

create table if not exists defect_type (
    defect_type_id bigint generated by default as identity primary key,
    code           text not null unique,
    name           text not null
);

create table if not exists inspector (
    inspector_id bigint generated by default as identity primary key,
    name         text not null unique
);

create table if not exists lot (
    lot_id        bigint generated by default as identity primary key,
    lot_no        text not null unique,
    part_id       bigint not null references part(part_id),
    received_date date not null,
    lot_qty       integer not null check (lot_qty between 2 and 35000),
    status        text not null default '대기' check (status in ('대기', '합격', '불합격'))
);

create table if not exists inspection (
    inspection_id bigint generated by default as identity primary key,
    lot_id        bigint not null references lot(lot_id),
    inspector_id  bigint not null references inspector(inspector_id),
    inspected_at  timestamp not null,
    severity      text not null check (severity in ('보통', '까다로운')),
    code_letter   text not null,
    sample_qty    integer not null check (sample_qty >= 1),
    ac            integer not null,
    re            integer not null,
    defective_qty integer not null check (defective_qty >= 0),
    result        text not null check (result in ('합격', '불합격')),
    remark        text,
    is_cancelled  boolean not null default false,
    cancel_reason text,
    cancelled_at  timestamp,
    -- [고정] 규칙 2를 DB에서도 한 번 더 지킨다
    constraint ck_defective_le_sample check (defective_qty <= sample_qty),
    constraint ck_re_is_ac_plus_1    check (re = ac + 1),
    constraint ck_result_matches     check (result = case when defective_qty <= ac then '합격' else '불합격' end),
    -- [고정] 규칙 3: 판정 취소는 사유 필수
    constraint ck_cancel_reason      check (not is_cancelled or (cancel_reason is not null and btrim(cancel_reason) <> ''))
);
-- 한 로트에는 '취소되지 않은' 검사가 하나만 있을 수 있다
create unique index if not exists ux_inspection_active_lot on inspection(lot_id) where not is_cancelled;

create table if not exists inspection_defect (
    inspection_id  bigint not null references inspection(inspection_id),
    defect_type_id bigint not null references defect_type(defect_type_id),
    qty            integer not null check (qty >= 0),
    primary key (inspection_id, defect_type_id)
);

create table if not exists aql_code_letter (
    code_letter text primary key,
    lot_min     integer not null,
    lot_max     integer not null,
    sample_size integer not null
);

create table if not exists aql_plan (
    code_letter text not null references aql_code_letter(code_letter),
    aql         numeric(4,2) not null,
    severity    text not null check (severity in ('보통', '까다로운')),
    plan_letter text not null,
    sample_size integer not null,
    ac          integer not null,
    re          integer not null,
    primary key (code_letter, aql, severity)
);

-- -----------------------------------------------------------------------------
-- 2. 조회용 뷰 (여러 테이블을 JOIN해 둔 '가상 표' — 화면은 이 뷰를 읽기만 한다)
-- -----------------------------------------------------------------------------
create or replace view v_part with (security_invoker = on) as
select p.part_id, p.part_no, p.name, p.supplier_id, s.name as supplier_name, p.aql, p.resumed_at
from part p join supplier s on s.supplier_id = p.supplier_id;

create or replace view v_pending_lot with (security_invoker = on) as
select l.lot_id, l.lot_no, l.received_date, l.lot_qty, p.part_id, p.part_no, p.name as part_name,
       s.name as supplier_name, p.aql
from lot l
join part p on p.part_id = l.part_id
join supplier s on s.supplier_id = p.supplier_id
where l.status = '대기';

create or replace view v_inspection with (security_invoker = on) as
select i.inspection_id, i.inspected_at, i.lot_id, l.lot_no, l.lot_qty, l.received_date,
       p.part_id, p.part_no, p.name as part_name, s.supplier_id, s.name as supplier_name,
       ins.name as inspector_name, i.severity, i.code_letter, i.sample_qty, i.ac, i.re,
       i.defective_qty, i.result, i.remark, i.is_cancelled, i.cancel_reason, i.cancelled_at
from inspection i
join lot l on l.lot_id = i.lot_id
join part p on p.part_id = l.part_id
join supplier s on s.supplier_id = p.supplier_id
join inspector ins on ins.inspector_id = i.inspector_id;

create or replace view v_inspection_defect with (security_invoker = on) as
select x.inspection_id, x.defect_type_id, d.name as defect_name, x.qty,
       i.inspected_at, i.is_cancelled, l.part_id, p.supplier_id
from inspection_defect x
join defect_type d on d.defect_type_id = x.defect_type_id
join inspection i on i.inspection_id = x.inspection_id
join lot l on l.lot_id = i.lot_id
join part p on p.part_id = l.part_id;

-- -----------------------------------------------------------------------------
-- 3. 여러 표를 한 번에 바꾸는 작업은 DB 함수로 (전부 성공하거나 전부 취소 = 트랜잭션)
-- -----------------------------------------------------------------------------
-- 판정 저장: 검사 1행 + 불량내역 여러 행 + 로트 상태 변경
create or replace function save_inspection(
    p_lot_id bigint, p_inspector_id bigint, p_inspected_at timestamp,
    p_severity text, p_code_letter text, p_sample_qty integer, p_ac integer, p_re integer,
    p_defective_qty integer, p_result text, p_remark text, p_defects jsonb)
returns bigint
language plpgsql
set search_path = public
as $$
declare
    v_status text;
    v_sum    integer;
    v_id     bigint;
begin
    select status into v_status from lot where lot_id = p_lot_id for update;
    if v_status is null then
        raise exception '로트를 찾을 수 없습니다.';
    end if;
    if v_status <> '대기' then
        raise exception '''대기'' 상태인 로트만 검사할 수 있습니다. (현재: %)', v_status;
    end if;

    select coalesce(sum((e->>'qty')::integer), 0) into v_sum
    from jsonb_array_elements(coalesce(p_defects, '[]'::jsonb)) e;
    if v_sum <> p_defective_qty then
        raise exception '불량유형별 수량의 합(%)과 불량품수(%)가 다릅니다.', v_sum, p_defective_qty;
    end if;

    insert into inspection(lot_id, inspector_id, inspected_at, severity, code_letter,
                           sample_qty, ac, re, defective_qty, result, remark)
    values (p_lot_id, p_inspector_id, p_inspected_at, p_severity, p_code_letter,
            p_sample_qty, p_ac, p_re, p_defective_qty, p_result, nullif(btrim(coalesce(p_remark, '')), ''))
    returning inspection_id into v_id;

    insert into inspection_defect(inspection_id, defect_type_id, qty)
    select v_id, (e->>'defect_type_id')::bigint, (e->>'qty')::integer
    from jsonb_array_elements(coalesce(p_defects, '[]'::jsonb)) e
    where (e->>'qty')::integer > 0;

    update lot set status = p_result where lot_id = p_lot_id;
    return v_id;
end;
$$;

-- 판정 취소: 사유 필수, 기록은 남기고 로트는 '대기'로
create or replace function cancel_inspection(p_inspection_id bigint, p_reason text, p_cancelled_at timestamp)
returns void
language plpgsql
set search_path = public
as $$
declare
    v_lot bigint;
begin
    if p_reason is null or btrim(p_reason) = '' then
        raise exception '판정 취소 사유를 입력해야 합니다.';
    end if;
    select lot_id into v_lot from inspection
    where inspection_id = p_inspection_id and not is_cancelled
    for update;
    if v_lot is null then
        raise exception '취소할 수 있는 검사가 아닙니다.';
    end if;
    update inspection set is_cancelled = true, cancel_reason = btrim(p_reason), cancelled_at = p_cancelled_at
    where inspection_id = p_inspection_id;
    update lot set status = '대기' where lot_id = v_lot;
end;
$$;

-- -----------------------------------------------------------------------------
-- 4. 권한 (로그인 없이 웹 주소만 알면 쓰는 앱 → anon 역할에 읽기·추가·수정 허용, 삭제는 허용 안 함)
-- -----------------------------------------------------------------------------
grant usage on schema public to anon, authenticated;
grant select, insert, update on supplier, part, defect_type, inspector, lot, inspection, inspection_defect
    to anon, authenticated;
grant select on aql_code_letter, aql_plan to anon, authenticated;
grant select on v_part, v_pending_lot, v_inspection, v_inspection_defect to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;
grant execute on function save_inspection(bigint, bigint, timestamp, text, text, integer, integer, integer, integer, text, text, jsonb)
    to anon, authenticated;
grant execute on function cancel_inspection(bigint, text, timestamp) to anon, authenticated;

-- 행 수준 보안(RLS): Supabase는 RLS를 켜야 안전 경고가 사라진다. 이 앱은 누구나 쓰는 앱이므로 '모두 허용' 규칙을 둔다.
do $$
declare
    t text;
begin
    foreach t in array array['supplier', 'part', 'defect_type', 'inspector', 'lot', 'inspection', 'inspection_defect'] loop
        execute format('alter table %I enable row level security', t);
        execute format('drop policy if exists "app_select" on %I', t);
        execute format('drop policy if exists "app_insert" on %I', t);
        execute format('drop policy if exists "app_update" on %I', t);
        execute format('create policy "app_select" on %I for select to anon, authenticated using (true)', t);
        execute format('create policy "app_insert" on %I for insert to anon, authenticated with check (true)', t);
        execute format('create policy "app_update" on %I for update to anon, authenticated using (true) with check (true)', t);
    end loop;
    foreach t in array array['aql_code_letter', 'aql_plan'] loop       -- AQL 기준표는 읽기만
        execute format('alter table %I enable row level security', t);
        execute format('drop policy if exists "app_select" on %I', t);
        execute format('create policy "app_select" on %I for select to anon, authenticated using (true)', t);
    end loop;
end;
$$;

